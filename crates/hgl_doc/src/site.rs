//! Builds the file://-ready HTML reference from the documentation model.
//! All generated destinations are relative to the page that uses them.

use std::borrow::Cow;
use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;

use hgl_analyser::Program;
use hgl_diagnostics::Location;
use serde::Serialize;

use crate::markdown::{Markup, Renderers, escaped, render, render_section};
use crate::model::{Declaration, Documentation, Interface, Model, Module, Section, Source};
use crate::{LinkContext, links, signatures};

/// The browser builds and notices from the exact npm releases in
/// vendor/README.md. Embedding them also carries them in release binaries.
const KATEX: &[(&str, &[u8])] = &[
    (
        "vendor/katex/katex.min.js",
        include_bytes!("../vendor/katex/katex.min.js"),
    ),
    (
        "vendor/katex/LICENSE",
        include_bytes!("../vendor/katex/LICENSE"),
    ),
];

const MERMAID: &[(&str, &[u8])] = &[
    (
        "vendor/mermaid/mermaid.min.js",
        include_bytes!("../vendor/mermaid/mermaid.min.js"),
    ),
    (
        "vendor/mermaid/LICENSE",
        include_bytes!("../vendor/mermaid/LICENSE"),
    ),
    (
        "vendor/mermaid/THIRD-PARTY-NOTICES.txt",
        include_bytes!("../vendor/mermaid/THIRD-PARTY-NOTICES.txt"),
    ),
];

/// A generated documentation page or asset.
pub struct SiteFile {
    /// Path relative to the output directory, using forward slashes.
    pub path: String,
    /// The generated page or asset bytes.
    pub contents: Cow<'static, [u8]>,
}

impl SiteFile {
    /// Text generated by the renderer is UTF-8 with LF line endings.
    fn text(path: impl Into<String>, text: String) -> Self {
        Self {
            path: path.into(),
            contents: Cow::Owned(text.into_bytes()),
        }
    }
}

struct Target<'a> {
    page: &'a str,
    anchor: String,
}

struct Site<'a> {
    program: &'a Program,
    targets: HashMap<Location, Target<'a>>,
    search: Vec<SearchEntry>,
}

/// One declaration in the offline search index. Module paths and anchors
/// are the same as the site's ordinary links.
#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct SearchEntry {
    canonical_name: String,
    href: String,
}

pub(crate) fn build(program: &Program, model: Model<'_>) -> Vec<SiteFile> {
    let pages: Vec<_> = model
        .modules
        .iter()
        .map(|module| filename(module.name))
        .collect();
    let mut site = Site {
        program,
        targets: HashMap::new(),
        search: Vec::new(),
    };
    for (module, page) in model.modules.iter().zip(&pages) {
        site.add_module_targets(module, page);
    }
    // The operator owns each candidate's article. Its implementing module
    // lists a reference to that same article rather than copying it.
    let mut contributions = BTreeMap::<_, Vec<_>>::new();
    for module in &model.modules {
        for operator in &module.declarations {
            for candidate in &operator.candidates {
                if candidate.source.module != module.name {
                    contributions
                        .entry(candidate.source.module)
                        .or_default()
                        .push((operator, candidate));
                }
            }
        }
    }
    for candidates in contributions.values_mut() {
        candidates.sort_by_key(|(_, candidate)| {
            (
                candidate.source.part,
                candidate.source.line,
                candidate.source.column,
            )
        });
    }

    let search = serde_json::to_string(&site.search).expect("the search index has only strings");
    let mut files = vec![
        SiteFile::text("site.css", include_str!("site.css").replace("\r\n", "\n")),
        // A classic script can load the index directly from file://.
        SiteFile::text(
            "search-index.js",
            format!("const hglDeclarations = {search};\n"),
        ),
        SiteFile::text("search.js", include_str!("search.js").replace("\r\n", "\n")),
    ];
    let mut renderers = Renderers::default();
    for (module, page) in model.modules.iter().zip(&pages) {
        let mut markup = site.module(
            module,
            page,
            contributions.get(module.name).map_or(&[], Vec::as_slice),
        );
        renderers.include(&markup.renderers);
        if markup.renderers.any() {
            markup
                .html
                .push_str("<script defer src=\"../renderers.js\"></script>\n");
        }
        files.push(SiteFile::text(
            format!("modules/{page}"),
            finish_page(markup.html),
        ));
    }
    if renderers.any() {
        files.push(SiteFile::text(
            "renderers.js",
            include_str!("renderers.js").replace("\r\n", "\n"),
        ));
    }
    for (needed, assets) in [(renderers.math, KATEX), (renderers.mermaid, MERMAID)] {
        if needed {
            files.extend(assets.iter().map(|&(path, contents)| SiteFile {
                path: path.to_owned(),
                contents: Cow::Borrowed(contents),
            }));
        }
    }
    // Publish the entry page after all of its targets have been written.
    files.push(SiteFile::text("index.html", index(&model, &pages)));
    files
}

/// Module paths can differ only in case. Encode uppercase ASCII so those
/// modules have separate pages on case-insensitive filesystems too.
fn filename(module: &str) -> String {
    let mut name = String::from("mod-");
    for byte in module.bytes() {
        if byte.is_ascii_uppercase() {
            write!(name, "~{byte:02x}").unwrap();
        } else {
            name.push(char::from(byte));
        }
    }
    if name.len() > 200 {
        // The digest uses the whole module name, including its original case.
        let digest = blake3::hash(module.as_bytes()).to_hex();
        name = format!("mod-@{digest}");
    }
    name.push_str(".html");
    name
}

fn index(model: &Model<'_>, pages: &[String]) -> String {
    let mut output = page("API reference", "");
    output.push_str(
        "<h1>API reference</h1>\n\
         <div id=\"declaration-search\" hidden>\n\
         <label for=\"declaration-query\">Search declarations</label>\n\
         <input id=\"declaration-query\" type=\"search\" autocomplete=\"off\" aria-controls=\"search-results\">\n\
         <p role=\"status\"></p><ul id=\"search-results\"></ul>\n</div>\n\
         <script defer src=\"search-index.js\"></script>\n<script defer src=\"search.js\"></script>\n\
         <h2>Modules</h2>\n<ul>\n",
    );
    for (module, page) in model.modules.iter().zip(pages) {
        writeln!(
            output,
            "<li><a href=\"modules/{}\">{}</a></li>",
            escaped(page),
            escaped(module.name)
        )
        .unwrap();
    }
    output.push_str("</ul>\n");
    finish_page(output)
}

fn page(title: &str, root: &str) -> String {
    // Local classic scripts have to run both from file:// and from a static
    // web server. SVG and MathML may use inline styles but never a remote asset.
    format!(
        "<!doctype html>\n<html lang=\"en\">\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; \
         script-src 'self' file:; style-src 'self' file: 'unsafe-inline'; \
         font-src 'self' file:; img-src data:; base-uri 'none'\">\n\
         <title>{}</title>\n<link rel=\"stylesheet\" href=\"{root}site.css\">\n\
         <body>\n<header><nav><a href=\"{root}index.html\">API reference</a></nav></header>\n<main>\n",
        escaped(title),
    )
}

fn finish_page(mut page: String) -> String {
    page.push_str("</main>\n</body>\n</html>\n");
    page
}

fn collect_declarations<'d, 'm>(
    declaration: &'d Declaration<'m>,
    public: bool,
    output: &mut Vec<(&'d Declaration<'m>, bool)>,
) {
    output.push((declaration, public));
    for item in declaration.candidates.iter().chain(&declaration.members) {
        collect_declarations(item, public, output);
    }
}

impl<'a> Site<'a> {
    fn add_module_targets(&mut self, module: &Module<'_>, page: &'a str) {
        let mut declarations = Vec::new();
        for declaration in &module.declarations {
            collect_declarations(declaration, declaration.exported, &mut declarations);
        }
        let mut occurrences = HashMap::<_, usize>::new();
        // Reserve the public destinations first, including candidates and
        // members of public declarations, so private duplicates cannot move them.
        for &(declaration, _) in declarations
            .iter()
            .filter(|(_, public)| *public)
            .chain(declarations.iter().filter(|(_, public)| !*public))
        {
            let count = occurrences.entry(declaration.name).or_default();
            *count += 1;
            let mut anchor = format!("decl-{}", declaration.name);
            if *count > 1 {
                write!(anchor, "-{count}").unwrap();
            }
            self.targets
                .insert(declaration.source.at, Target { page, anchor });
        }
        for (declaration, _) in declarations {
            // Search locates an operator on the same page as its candidates.
            if !matches!(
                declaration.kind,
                "candidate" | "nativeCandidate" | "nativeCandidateImplementation"
            ) {
                let Target { anchor, .. } = &self.targets[&declaration.source.at];
                self.search.push(SearchEntry {
                    canonical_name: declaration.canonical_name.clone(),
                    href: format!("modules/{page}#{anchor}"),
                });
            }
        }
    }

    fn module(
        &self,
        module: &Module<'_>,
        page_name: &str,
        contributions: &[(&Declaration<'_>, &Declaration<'_>)],
    ) -> Markup {
        let mut output = Markup {
            html: page(module.name, "../"),
            renderers: Renderers::default(),
        };
        output.heading(1, module.name);
        for part in &module.parts {
            if let Some(comment) = &part.documentation {
                let level = if let Some(name) = part.name {
                    output.heading(2, &format!("Part {name}"));
                    2
                } else {
                    1
                };
                self.documentation(&mut output, comment, &part.source, page_name, level, None);
            }
        }

        let mut kinds = BTreeMap::<_, Vec<_>>::new();
        for declaration in &module.declarations {
            kinds
                .entry(group(declaration.kind))
                .or_default()
                .push(declaration);
        }
        if !kinds.is_empty() || !contributions.is_empty() {
            output
                .html
                .push_str("<nav class=\"contents\" aria-label=\"Module contents\">\n");
            output.heading(2, "Contents");
            output.html.push_str("<ul>\n");
            for (kind, declarations) in &kinds {
                writeln!(output.html, "<li>{}<ul>", escaped(kind)).unwrap();
                for declaration in declarations {
                    self.contents_entry(&mut output, declaration, page_name, declaration.name);
                }
                output.html.push_str("</ul></li>\n");
            }
            if !contributions.is_empty() {
                output
                    .html
                    .push_str("<li>Candidates for other modules<ul>\n");
                for (operator, candidate) in contributions {
                    self.contents_entry(
                        &mut output,
                        candidate,
                        page_name,
                        &operator.canonical_name,
                    );
                }
                output.html.push_str("</ul></li>\n");
            }
            output.html.push_str("</ul>\n</nav>\n");
        }
        for (kind, declarations) in kinds {
            output.heading(2, kind);
            for declaration in declarations {
                self.declaration(&mut output, declaration, page_name, 3);
            }
        }
        if !contributions.is_empty() {
            output.heading(2, "Candidates for other modules");
            output.html.push_str("<ul>\n");
            for (operator, candidate) in contributions {
                let href = self.destination(&self.targets[&candidate.source.at], page_name);
                writeln!(output.html, "<li><a href=\"{}\">{}</a>\n<pre class=\"signature\"><code>{}</code></pre></li>",
                    escaped(&href), escaped(&operator.canonical_name),
                    self.signature(candidate, page_name)).unwrap();
            }
            output.html.push_str("</ul>\n");
        }
        output
    }

    fn contents_entry(&self, output: &mut Markup, item: &Declaration<'_>, page: &str, label: &str) {
        let href = self.destination(&self.targets[&item.source.at], page);
        writeln!(
            output.html,
            "<li><a href=\"{}\">{}</a></li>",
            escaped(&href),
            escaped(label)
        )
        .unwrap();
    }

    fn destination(&self, target: &Target<'_>, page: &str) -> String {
        let prefix = if target.page == page { "" } else { target.page };
        format!("{prefix}#{}", target.anchor)
    }

    fn link(&self, source: &Source<'_>, page: &str, name: &str) -> Option<String> {
        let context = LinkContext {
            module: source.module,
            at: source.at,
        };
        let target = links::resolve(self.program, context, name)?;
        Some(self.destination(self.targets.get(&target)?, page))
    }

    fn signature(&self, declaration: &Declaration<'_>, page: &str) -> String {
        signatures::render(&declaration.signature, |name| {
            self.link(&declaration.source, page, name)
        })
    }

    fn declaration(
        &self,
        output: &mut Markup,
        declaration: &Declaration<'_>,
        page: &str,
        level: usize,
    ) {
        let Target { anchor, .. } = &self.targets[&declaration.source.at];
        writeln!(output.html, "<article id=\"{}\">", escaped(anchor)).unwrap();
        output.heading(level, declaration.name);
        writeln!(
            output.html,
            "<pre class=\"signature\"><code>{}</code></pre>",
            self.signature(declaration, page),
        )
        .unwrap();
        output.html.push_str("<p class=\"source\">");
        let origin = filename(declaration.source.module);
        if origin != page {
            write!(
                output.html,
                "Declared in <a href=\"{}\">{}</a>: ",
                escaped(&origin),
                escaped(declaration.source.module)
            )
            .unwrap();
        }
        writeln!(
            output.html,
            "{}:{}</p>",
            escaped(&declaration.source.file),
            declaration.source.line,
        )
        .unwrap();

        if let Some(comment) = &declaration.documentation {
            self.documentation(
                output,
                comment,
                &declaration.source,
                page,
                level,
                Some(&declaration.interface),
            );
        } else {
            generic_table(output, &declaration.interface, level + 1, None, |_| None);
            parameter_tables(output, &declaration.interface, level + 1, None, |_| None);
        }
        for (label, nested) in [
            ("Candidates", &declaration.candidates),
            ("Members", &declaration.members),
        ] {
            if !nested.is_empty() {
                output.heading(level + 1, label);
                for item in nested {
                    self.declaration(output, item, page, level + 2);
                }
            }
        }
        output.html.push_str("</article>\n");
    }

    fn documentation(
        &self,
        output: &mut Markup,
        comment: &Documentation,
        source: &Source<'_>,
        page: &str,
        level: usize,
        interface: Option<&Interface<'_>>,
    ) {
        let link = |name: &str| self.link(source, page, name);

        render(output, &comment.summary, level, link);
        let section_level = level + 1;
        let mut wrote_generics = false;
        let mut wrote_parameters = false;
        let has_generics = comment
            .sections
            .iter()
            .any(|section| section.recognized && section.heading.as_deref() == Some("Type Args:"));
        let has_parameters = comment
            .sections
            .iter()
            .any(|section| section.recognized && section.heading.as_deref() == Some("Args:"));
        for section in &comment.sections {
            // Keep introductory prose together. Missing interface tables
            // precede the first authored section instead of following its
            // examples or rules; explicit table sections keep their order.
            if section.heading.is_some()
                && let Some(interface) = interface
            {
                if !has_generics && !wrote_generics {
                    generic_table(output, interface, section_level, None, link);
                    wrote_generics = true;
                }
                if !has_parameters
                    && !wrote_parameters
                    && section.heading.as_deref() != Some("Type Args:")
                {
                    parameter_tables(output, interface, section_level, None, link);
                    wrote_parameters = true;
                }
            }
            match (section.heading.as_deref(), interface) {
                (Some("Type Args:"), Some(interface))
                    if section.recognized && !interface.generic_parameters.is_empty() =>
                {
                    generic_table(output, interface, section_level, Some(section), link);
                    render(output, &section.prose, section_level, link);
                    wrote_generics = true;
                }
                (Some("Args:"), Some(interface))
                    if section.recognized
                        && (!interface.parameters.is_empty()
                            || !interface.configuration_parameters.is_empty()) =>
                {
                    parameter_tables(output, interface, section_level, Some(section), link);
                    render(output, &section.prose, section_level, link);
                    wrote_parameters = true;
                }
                _ => {
                    let parent_level = if let Some(heading) = &section.heading {
                        // Use the same inline Markdown rules as the section text.
                        let title = heading.strip_suffix(':').unwrap_or(heading);
                        render(output, &format!("# {title} #"), level, link);
                        section_level
                    } else {
                        level
                    };
                    render_section(
                        output,
                        &section.text,
                        parent_level,
                        section.recognized && section.heading.as_deref() == Some("Examples:"),
                        link,
                    );
                }
            }
        }
        if let Some(interface) = interface {
            if !wrote_generics {
                generic_table(output, interface, section_level, None, link);
            }
            if !wrote_parameters {
                parameter_tables(output, interface, section_level, None, link);
            }
        }
    }
}

fn group(kind: &str) -> &'static str {
    match kind {
        "constant" => "Constants",
        "enum" => "Enums",
        "function" => "Functions",
        "nativeFunction" | "nativeImplementation" => "Native functions",
        "nativeType" => "Native types",
        "operator" => "Operators",
        "struct" => "Structs",
        "test" => "Tests",
        _ => "Other declarations",
    }
}

struct Row<'a> {
    name: &'a str,
    mode: &'static str,
    ty: Cow<'a, str>,
    default: Option<&'a str>,
}

fn generic_table(
    output: &mut Markup,
    interface: &Interface<'_>,
    level: usize,
    section: Option<&Section>,
    link: impl Fn(&str) -> Option<String> + Copy,
) {
    table(
        output,
        "Type arguments",
        level,
        interface.generic_parameters.iter().map(|parameter| Row {
            name: parameter.name,
            mode: "",
            ty: Cow::Borrowed(parameter.ty.as_deref().unwrap_or(match parameter.kind {
                "plain" | "type" => "type",
                _ => parameter.kind,
            })),
            default: parameter.default.as_deref(),
        }),
        section,
        link,
    );
}

fn parameter_tables(
    output: &mut Markup,
    interface: &Interface<'_>,
    level: usize,
    section: Option<&Section>,
    link: impl Fn(&str) -> Option<String> + Copy,
) {
    for (heading, parameters) in [
        ("Arguments", &interface.parameters),
        ("Configuration", &interface.configuration_parameters),
    ] {
        table(
            output,
            heading,
            level,
            parameters.iter().map(|parameter| {
                let mode = if parameter.constant {
                    "const "
                } else if parameter.var {
                    "var "
                } else if parameter.reference {
                    "ref "
                } else {
                    ""
                };
                let ty = match parameter.pack {
                    Some("positional") => Cow::Owned(format!("...{}", parameter.ty)),
                    Some("named") => Cow::Owned(format!("...{{{}}}", parameter.ty)),
                    _ => Cow::Borrowed(parameter.ty.as_str()),
                };
                Row {
                    name: parameter.name,
                    mode,
                    ty,
                    default: parameter.default.as_deref(),
                }
            }),
            section,
            link,
        );
    }
}

fn table<'a>(
    output: &mut Markup,
    heading: &str,
    level: usize,
    rows: impl ExactSizeIterator<Item = Row<'a>>,
    section: Option<&Section>,
    link: impl Fn(&str) -> Option<String> + Copy,
) {
    if rows.len() == 0 {
        return;
    }
    output.heading(level, heading);
    writeln!(
        output.html,
        "<table><thead><tr><th scope=\"col\">Name</th><th scope=\"col\">Type</th>\n\
         <th scope=\"col\">Default</th><th scope=\"col\">Description</th></tr></thead><tbody>"
    )
    .unwrap();
    for row in rows {
        write!(
            output.html,
            "<tr><th scope=\"row\"><code>{}{}</code></th><td><code>{}</code></td><td>",
            row.mode,
            escaped(row.name),
            escaped(&row.ty)
        )
        .unwrap();
        if let Some(value) = row.default {
            write!(output.html, "<code>{}</code>", escaped(value)).unwrap();
        } else {
            output.html.push('—');
        }
        output.html.push_str("</td><td>");
        for entry in section.into_iter().flat_map(|section| &section.entries) {
            if entry.key == row.name {
                render(output, &entry.text, level, link);
            }
        }
        output.html.push_str("</td></tr>\n");
    }
    output.html.push_str("</tbody></table>\n");
}
